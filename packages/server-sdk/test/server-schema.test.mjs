function paired(interfaces) {
  const bytes = encode(interfaces),
    custom = new Uint8Array([...new Enc().str("hd.capabilities").done(), ...bytes]);
  const module = new WebAssembly.Module(
    new Uint8Array([0, 97, 115, 109, 1, 0, 0, 0, ...new Enc().leb(0).bytes(custom).done()]),
  );
  const section = new Uint8Array(WebAssembly.Module.customSections(module, "hd.capabilities")[0]);
  const companion = `// Generated by hd; do not edit.\nexport const abiVersion = 1;\nexport const contract = new Uint8Array([${section}]);\nthrow Error('untrusted code must never execute');\n`;
  checkCompanionPairing(companion, section);
  return readPackageContract(section);
}
