// This reads only the compiler companion's data header, never its JS body.
// Code after the header is neither evaluated nor copied into deployed output.
export function checkCompanionPairing(source, bytes) {
  if (typeof source !== "string") {
    source = new TextDecoder("utf-8", { fatal: true }).decode(source);
  }
  const match =
    /^\/\/ Generated by hd; do not edit\.\r?\nexport const abiVersion = (\d+);\r?\nexport const contract = new Uint8Array\((\[[\d,]*\])\);\r?\n/.exec(
      source,
    );
  if (!match) {
    throw new Error("unrecognized generated companion data header");
  }
  let values;
  try {
    values = JSON.parse(match[2]);
  } catch {
    throw new Error("invalid companion contract byte array");
  }
  if (
    !(bytes instanceof Uint8Array) ||
    bytes.length < 4 ||
    !values.every((n) => Number.isInteger(n) && n >= 0 && n <= 255) ||
    values.length !== bytes.length ||
    values.some((n, i) => n !== bytes[i]) ||
    Number(match[1]) !==
      new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength).getUint32(0, true)
  ) {
    throw new Error("companion data does not match Wasm contract");
  }
}

// Only the SDK's two fixed output layouts are accepted. Artifact JS is ignored.
export function fixedBindingsModule(bytes, runtimeDirectory = "host") {
  if (!(bytes instanceof Uint8Array)) {
    throw new Error("contract must be bytes");
  }
  if (!["host", "runtime"].includes(runtimeDirectory)) {
    throw new Error("unknown fixed runtime layout");
  }
  return `import { contractBindings } from "./sdk/contract-bindings.mjs";
import { readPackageContract } from "./${runtimeDirectory}/package-providers.js";
const bindings = contractBindings(new Uint8Array([${bytes.join(",")}]), readPackageContract);
export const abiVersion = bindings.abiVersion;
export const contract = bindings.contract;
export const interfaces = bindings.interfaces;
export const bind = bindings.bind;
`;
}
