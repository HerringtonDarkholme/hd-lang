import { Enc } from "../../../../host/wire.ts";
function value(error, [tag, left, right]) {
  error.leb(tag);
  const fields = (fs) => {
    error.leb(fs.length);
    for (const [count, text] of fs) {
      error.str(count);
      value(error, text);
    }
  };
  if (tag === 3) {
    error.leb(left).leb(right ? 1 : 0);
  } else if (tag === 8 || tag === 9) {
    value(error, left);
  } else if (tag === 10) {
    error.leb(left.length);
    for (const text of left) {
      value(error, text);
    }
  } else if (tag === 11) {
    fields(left);
  } else if (tag === 12) {
    error.leb(left.length);
    for (const [count, fs] of left) {
      error.str(count);
      fields(fs);
    }
  } else if (tag === 13) {
    value(error, left);
    value(error, right);
  } else if (tag === 15) {
    error.str(left);
  }
}
export function encode(interfaces) {
  const error = new Enc();
  error.leb(interfaces.length);
  for (const i of interfaces) {
    error.str(i.identity.package).str(i.identity.version).str(i.identity.trait_path).str(i.module);
    error.leb(i.selectors.length);
    for (const source of i.selectors) {
      error.str(source);
    }
    error.leb(i.handle ? 1 : 0).leb(i.methods.length);
    for (const message of i.methods) {
      error
        .str(message.name)
        .str(message.member)
        .leb(message.wait === "may" ? 1 : 0)
        .leb(message.params.length);
      for (const path of message.params) {
        value(error, path);
      }
      value(error, message.result);
    }
  }
  return new Uint8Array([1, 0, 0, 0, ...error.done()]);
}

export function contractSection(wasm) {
  const sections = WebAssembly.Module.customSections(
    new WebAssembly.Module(wasm),
    "hd.capabilities",
  );
  if (sections.length !== 1) {
    throw Error("expected exactly one contract");
  }
  return new Uint8Array(sections[0]);
}
function leb(bytes, at) {
  let value = 0,
    shift = 0;
  for (;;) {
    const byte = bytes[at++];
    value |= (byte & 127) << shift;
    if (!(byte & 128)) {
      return [value, at];
    }
    shift += 7;
  }
}
export function transformSection(wasm, transform) {
  const parts = [wasm.subarray(0, 8)];
  for (let at = 8; at < wasm.length;) {
    const id = wasm[at++],
      [length, body] = leb(wasm, at);
    at = body + length;
    const bytes = transform(id, wasm.subarray(body, at));
    parts.push(Buffer.from(new Enc().leb(id).bytes(bytes).done()));
  }
  return Buffer.concat(parts);
}
export function withContract(wasm, contract) {
  return transformSection(wasm, (id, bytes) => {
    if (id === 0) {
      const [length, at] = leb(bytes, 0);
      if (bytes.subarray(at, at + length).toString("utf8") === "hd.capabilities") {
        return new Uint8Array([...new Enc().str("hd.capabilities").done(), ...contract]);
      }
    }
    return bytes;
  });
}
export function withImportModule(wasm, before, after) {
  let changed = false;
  const result = transformSection(wasm, (id, bytes) => {
    if (id !== 2) {
      return bytes;
    }
    const needle = Buffer.from(new Enc().str(before).done());
    const at = bytes.indexOf(needle);
    if (at < 0) {
      throw Error("expected import module " + before);
    }
    changed = true;
    return Buffer.concat([
      bytes.subarray(0, at),
      Buffer.from(new Enc().str(after).done()),
      bytes.subarray(at + needle.length),
    ]);
  });
  if (!changed) {
    throw Error("expected import section");
  }
  new WebAssembly.Module(result);
  return result;
}
export function companionHeader(contract) {
  return `// Generated by hd; do not edit.\nexport const abiVersion = 1;\nexport const contract = new Uint8Array([${contract}]);\n`;
}
