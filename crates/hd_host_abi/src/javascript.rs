//! Signature-specific JavaScript glue for package host traits. All text
//! derived from a declaration is escaped data; helpers come from the host.

use crate::c::{Num, Param, Ret, Table};
use crate::schema::{Contract, Field, VERSION, Value};
use std::fmt::Write as _;

/// Generate an ES module without imports, eval, or provider implementation
/// code. Its invoker passes the trusted host helpers and plain JS providers.
/// A trait bound to a C provider has a table in `c_tables`: its methods'
/// imports take C arguments (`module.host.package.c-types`), which the
/// glue describes beside the contract, with the `hd.c` section's bytes
/// the runtime checks against the guest's.
///
/// Cost: one pass over the contract and the tables.
pub fn generate(contract: &Contract, c_tables: &[Table]) -> Result<String, &'static str> {
    contract.validate()?;
    if contract.interfaces.is_empty() {
        return Ok(String::new());
    }
    let mut out = format!(
        "// Generated by hd; do not edit.\nexport const abiVersion = {VERSION};\nexport const contract = new Uint8Array(["
    );
    for (n, b) in contract.encode().iter().enumerate() {
        if n != 0 {
            out.push(',');
        }
        let _ = write!(out, "{b}");
    }
    out.push_str("]);\nconst checkedContract = contract.slice();\nexport const interfaces = Object.freeze([\n");
    for i in &contract.interfaces {
        let _ = write!(
            out,
            "  Object.freeze({{ identity: Object.freeze({{ package: {}, version: {}, trait_path: {} }}), module: {}, handle: {}, selectors: Object.freeze([",
            quoted(&i.identity.package),
            quoted(&i.identity.version),
            quoted(&i.identity.trait_path),
            quoted(&i.module),
            i.handle
        );
        for (n, selector) in i.selectors.iter().enumerate() {
            if n != 0 {
                out.push(',');
            }
            out.push_str(&quoted(selector));
        }
        out.push_str("]) }),\n");
    }
    out.push_str(
        "]);\nexport function bind(runtime, implementations) {\n  if (!(implementations instanceof Map)) throw new Error('provider implementations must be a map keyed by interface module');\n  const roots = interfaces.filter(i => !i.handle);\n  for (const key of implementations.keys()) {\n    if (!roots.some(i => i.module === key)) throw new Error('implementation names no required package capability');\n  }\n  const providers = roots.map(i => {\n    if (!implementations.has(i.module)) throw new Error('missing package provider implementation');\n    return Object.freeze({ identity: i.identity, module: i.module, contract: checkedContract.slice(), implementation: implementations.get(i.module) });\n  });\n  return runtime.bind(checkedContract.slice(), [\n"
    );
    for i in &contract.interfaces {
        let _ = writeln!(
            out,
            "    {{ module: {}, handle: {}, methods: [",
            quoted(&i.module),
            i.handle
        );
        for m in &i.methods {
            let _ = write!(
                out,
                "      {{ name: {}, member: {}, wait: {}, params: [",
                quoted(&m.name),
                quoted(&m.member),
                quoted(if m.suspends { "may" } else { "never" })
            );
            for (n, p) in m.params.iter().enumerate() {
                if n != 0 {
                    out.push(',');
                }
                codec(&mut out, &p.value);
            }
            out.push_str("], result: ");
            codec(&mut out, &m.result);
            out.push_str(" },\n");
        }
        out.push_str("    ] },\n");
    }
    out.push_str("  ], providers, ");
    c_methods(&mut out, c_tables);
    out.push_str(");\n}\n");
    Ok(out)
}

/// The C argument and result kinds of each C-bound interface's methods,
/// by import module and method name, with the `hd.c` section's bytes; or
/// `null` for a contract with no C-bound interface.
fn c_methods(out: &mut String, tables: &[Table]) {
    if tables.is_empty() {
        out.push_str("null");
        return;
    }
    out.push_str("{ section: new Uint8Array([");
    for (n, b) in crate::c::encode(tables).iter().enumerate() {
        if n != 0 {
            out.push(',');
        }
        let _ = write!(out, "{b}");
    }
    out.push_str("]), methods: {");
    // A returned handle names its trait; the runtime keys handles by the
    // handle interface's module.
    let handles: hd_base::HashMap<&str, &str> = tables
        .iter()
        .filter(|t| t.handle)
        .map(|t| (t.trait_name.as_str(), t.module.as_str()))
        .collect();
    for (n, t) in tables.iter().enumerate() {
        if n != 0 {
            out.push(',');
        }
        let _ = write!(out, " {}: {{", quoted(&t.module));
        for (k, m) in t.methods.iter().enumerate() {
            if k != 0 {
                out.push(',');
            }
            let _ = write!(out, " {}: {{ params: [", quoted(&m.name));
            for (j, (_, p)) in m.params.iter().enumerate() {
                if j != 0 {
                    out.push(',');
                }
                let _ = match *p {
                    Param::Bool => write!(out, "[\"bool\"]"),
                    Param::Num(n) => write!(out, "[\"num\",\"{}\"]", num(n)),
                    Param::Ref { num: n, mutable } => {
                        write!(out, "[\"ref\",\"{}\",{mutable}]", num(n))
                    }
                    Param::List { num: n, mutable } => {
                        write!(out, "[\"list\",\"{}\",{mutable}]", num(n))
                    }
                    Param::Str => write!(out, "[\"str\"]"),
                };
            }
            out.push_str("], result: ");
            ret(out, &m.result, &handles);
            out.push_str(" }");
        }
        out.push_str(" }");
    }
    out.push_str(" } }");
}

fn ret(out: &mut String, r: &Ret, handles: &hd_base::HashMap<&str, &str>) {
    match r {
        Ret::Void => out.push_str("[\"void\"]"),
        Ret::Bool => out.push_str("[\"bool\"]"),
        Ret::Num(n) => {
            let _ = write!(out, "[\"num\",\"{}\"]", num(*n));
        }
        Ret::Bytes => out.push_str("[\"bytes\"]"),
        Ret::Result(inner) => {
            out.push_str("[\"result\",");
            ret(out, inner, handles);
            out.push(']');
        }
        Ret::Handle(name) => {
            let module = handles.get(name.as_str()).copied().unwrap_or("");
            let _ = write!(out, "[\"handle\",{}]", quoted(module));
        }
    }
}

/// A C number's hd name, which the JS runtime keys its views by.
fn num(n: Num) -> &'static str {
    match n {
        Num::I8 => "i8",
        Num::I16 => "i16",
        Num::I32 => "i32",
        Num::I64 => "i64",
        Num::U8 => "u8",
        Num::U16 => "u16",
        Num::U32 => "u32",
        Num::U64 => "u64",
        Num::Usize => "usize",
        Num::F32 => "f32",
        Num::F64 => "f64",
    }
}

fn fields(out: &mut String, fs: &[Field]) {
    out.push('[');
    for (n, f) in fs.iter().enumerate() {
        if n != 0 {
            out.push(',');
        }
        let _ = write!(out, "[{},", quoted(&f.name));
        codec(out, &f.value);
        out.push(']');
    }
    out.push(']');
}

fn codec(out: &mut String, v: &Value) {
    match v {
        Value::Void => out.push_str("runtime.unit"),
        Value::Bool => out.push_str("runtime.bool"),
        Value::Char => out.push_str("runtime.char"),
        Value::F32 => out.push_str("runtime.f32"),
        Value::F64 => out.push_str("runtime.f64"),
        Value::String => out.push_str("runtime.str"),
        Value::Bytes => out.push_str("runtime.bytes"),
        Value::Json => out.push_str("runtime.json"),
        Value::Never => out.push_str("runtime.never"),
        Value::Int { bits, signed } => {
            let _ = write!(out, "runtime.int({bits},{signed})");
        }
        Value::Handle(module) => {
            let _ = write!(out, "runtime.handle({})", quoted(module));
        }
        Value::List(t) | Value::Option(t) => {
            out.push_str(if matches!(v, Value::List(_)) {
                "runtime.list("
            } else {
                "runtime.option("
            });
            codec(out, t);
            out.push(')');
        }
        Value::Tuple(ts) => {
            out.push_str("runtime.tuple([");
            for (n, t) in ts.iter().enumerate() {
                if n != 0 {
                    out.push(',');
                }
                codec(out, t);
            }
            out.push_str("])");
        }
        Value::Record(_, fs) => {
            out.push_str("runtime.record(");
            fields(out, fs);
            out.push(')');
        }
        Value::Enum(_, vs) => {
            out.push_str("runtime.enumeration([");
            for (n, v) in vs.iter().enumerate() {
                if n != 0 {
                    out.push(',');
                }
                let _ = write!(out, "[{},", quoted(&v.name));
                fields(out, &v.fields);
                out.push(']');
            }
            out.push_str("])");
        }
        Value::Map(k, v) => {
            out.push_str("runtime.map(");
            codec(out, k);
            out.push(',');
            codec(out, v);
            out.push(')');
        }
        Value::Result(a, b) => {
            out.push_str("runtime.result(");
            codec(out, a);
            out.push(',');
            codec(out, b);
            out.push(')');
        }
        // One codec per recursive type: `r<id>` is the codec being built,
        // which its own body calls.
        Value::Rec(id, body) => {
            let _ = write!(out, "runtime.rec({id},r{id}=>");
            codec(out, body);
            out.push(')');
        }
        Value::Ref(id) => {
            let _ = write!(out, "r{id}");
        }
    }
}

fn quoted(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\u{0000}'..='\u{001f}' | '\u{2028}' | '\u{2029}' => {
                let _ = write!(out, "\\u{:04x}", u32::from(c));
            }
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Write as _;
    use std::process::Stdio;

    /// A C-bound interface's glue names each method's C argument and
    /// result kinds, with the `hd.c` section's bytes; other glue passes
    /// `null`.
    #[test]
    fn c_bound_glue_describes_c_arguments_beside_the_contract() {
        use crate::c::{Method, Num, Param, Ret, Table};
        let contract = crate::schema::tests::sample();
        assert!(
            generate(&contract, &[])
                .unwrap()
                .contains("], providers, null);")
        );
        let root = contract.interfaces.iter().find(|i| !i.handle).unwrap();
        let table = Table {
            module: root.module.clone(),
            trait_name: "Store".into(),
            handle: false,
            methods: vec![
                Method {
                    name: "put".into(),
                    params: vec![
                        ("path".into(), Param::Str),
                        (
                            "into".into(),
                            Param::List {
                                num: Num::I32,
                                mutable: true,
                            },
                        ),
                        (
                            "at".into(),
                            Param::Ref {
                                num: Num::U64,
                                mutable: false,
                            },
                        ),
                        ("on".into(), Param::Bool),
                        ("x".into(), Param::Num(Num::F32)),
                    ],
                    result: Ret::Num(Num::Usize),
                    suspends: false,
                },
                Method {
                    name: "take".into(),
                    params: Vec::new(),
                    result: Ret::Result(Box::new(Ret::Bytes)),
                    suspends: true,
                },
            ],
        };
        let glue = generate(&contract, std::slice::from_ref(&table)).unwrap();
        let section: Vec<String> = crate::c::encode(&[table])
            .iter()
            .map(u8::to_string)
            .collect();
        assert!(glue.contains(&format!(
            "{{ section: new Uint8Array([{}]), methods: {{ {}: {{",
            section.join(","),
            quoted(&root.module)
        )));
        assert!(glue.contains(r#""put": { params: [["str"],["list","i32",true],["ref","u64",false],["bool"],["num","f32"]], result: ["num","usize"] }"#));
        assert!(glue.contains(r#""take": { params: [], result: ["result",["bytes"]] }"#));
    }

    #[test]
    fn ordinary_programs_emit_no_glue() {
        assert_eq!(generate(&Contract::default(), &[]).unwrap(), "");
    }

    #[test]
    fn generated_module_is_executable_data_safe_and_signature_specific() {
        let mut c = crate::schema::tests::sample();
        // Raw names cannot inject module code, alter prototypes, or break strings.
        c.interfaces[0].methods[0].name = "__proto__\"\\\n\u{2028}".into();
        let glue = generate(&c, &[]).unwrap();
        let script = format!(
            r"
const exports = await import('data:text/javascript,' + encodeURIComponent({}));
const {{ bind, contract, abiVersion, interfaces }} = exports;
if ('defineProvider' in exports) throw Error('provider selector API remains');
const implementation = {{ echo() {{}} }};
const implementations = new Map([[interfaces[0].module, implementation]]);
contract.fill(0);
for (const bad of [[], new Map(), new Map([['missing', implementation]])]) {{
  let refused = false;
  try {{ bind({{}}, bad); }} catch {{ refused = true; }}
  if (!refused) throw Error('invalid implementation map accepted');
}}
let called = 0;
const runtime = new Proxy({{
  bind(bytes, interfaces, providers) {{
    if (abiVersion !== 2 || bytes.length !== contract.length) throw Error('wrong ABI');
    if (interfaces[0].methods[0].name !== {}) throw Error('name changed');
    if (interfaces[0].methods[0].wait !== 'may' || interfaces[1].methods[0].wait !== 'never') throw Error('wait changed');
    if (interfaces[0].methods[0].params.length !== 14) throw Error('parameters changed');
    if (interfaces[0].methods[0].params[2] !== 'int:64,true') throw Error('integer type changed');
    if (interfaces[0].methods[0].params[11] !== 'record:text,str') throw Error('record fields lost');
    if (bytes[0] !== 2 || providers.length !== 1) throw Error('contract or provider count changed');
    const provider = providers[0];
    if (provider.implementation !== implementation || provider.identity !== exports.interfaces[0].identity) throw Error('plain provider identity lost');
    if (!Object.isFrozen(provider) || !Object.isFrozen(provider.identity)) throw Error('mutable identity');
    if (provider.contract[0] !== 2) throw Error('exported bytes altered registration');
    called++;
    return interfaces;
  }}
}}, {{ get(o, k) {{ return k in o ? o[k] : ['unit','bool','char','f32','f64','str','bytes','json'].includes(k) ? k : (...xs) => k + ':' + xs.flat(Infinity).join(','); }} }});
bind(runtime, implementations);
if (called !== 1) throw Error('binding missing');
console.log('generated glue ok');
",
            quoted(&glue),
            quoted(&c.interfaces[0].methods[0].name)
        );
        let mut child = hd_testkit::node::command()
            .args(["--input-type=module"])
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .expect("Node for JS adapter tests");
        child
            .stdin
            .take()
            .unwrap()
            .write_all(script.as_bytes())
            .unwrap();
        let out = child.wait_with_output().unwrap();
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stderr)
        );
        assert_eq!(out.stdout, b"generated glue ok\n");
    }
}
