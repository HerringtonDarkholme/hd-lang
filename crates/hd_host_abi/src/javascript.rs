//! Signature-specific JavaScript glue for package host traits. All text
//! derived from a declaration is escaped data; helpers come from the host.

use crate::schema::{Contract, Field, VERSION, Value};
use std::fmt::Write as _;

/// Generate an ES module without imports, eval, or provider implementation
/// code. Its invoker passes the trusted host helpers and plain JS providers.
pub fn generate(contract: &Contract) -> Result<String, &'static str> {
    contract.validate()?;
    if contract.interfaces.is_empty() {
        return Ok(String::new());
    }
    let mut out = format!(
        "// Generated by hd; do not edit.\nexport const abiVersion = {VERSION};\nexport const contract = new Uint8Array(["
    );
    for (n, b) in contract.encode().iter().enumerate() {
        if n != 0 {
            out.push(',');
        }
        let _ = write!(out, "{b}");
    }
    out.push_str("]);\nconst checkedContract = contract.slice();\nexport const interfaces = Object.freeze([\n");
    for i in &contract.interfaces {
        let _ = write!(
            out,
            "  Object.freeze({{ identity: Object.freeze({{ package: {}, version: {}, trait_path: {} }}), module: {}, handle: {}, selectors: Object.freeze([",
            quoted(&i.identity.package),
            quoted(&i.identity.version),
            quoted(&i.identity.trait_path),
            quoted(&i.module),
            i.handle
        );
        for (n, selector) in i.selectors.iter().enumerate() {
            if n != 0 {
                out.push(',');
            }
            out.push_str(&quoted(selector));
        }
        out.push_str("]) }),\n");
    }
    out.push_str("]);\nexport function defineProvider(selector, implementation) {\n  const matches = interfaces.filter(i => !i.handle && (typeof selector === 'string'\n    ? i.module === selector || i.selectors.includes(selector)\n    : selector && ['package', 'version', 'trait_path'].every(k => i.identity[k] === selector[k])));\n  if (matches.length !== 1) throw new Error('provider selector must identify exactly one package capability');\n  const i = matches[0];\n  return Object.freeze({ identity: i.identity, module: i.module, contract: checkedContract.slice(), implementation });\n}\nexport function bind(runtime, providers) {\n  return runtime.bind(checkedContract.slice(), [\n");
    for i in &contract.interfaces {
        let _ = writeln!(
            out,
            "    {{ module: {}, handle: {}, methods: [",
            quoted(&i.module),
            i.handle
        );
        for m in &i.methods {
            let _ = write!(
                out,
                "      {{ name: {}, member: {}, wait: {}, params: [",
                quoted(&m.name),
                quoted(&m.member),
                quoted(if m.suspends { "may" } else { "never" })
            );
            for (n, p) in m.params.iter().enumerate() {
                if n != 0 {
                    out.push(',');
                }
                codec(&mut out, p);
            }
            out.push_str("], result: ");
            codec(&mut out, &m.result);
            out.push_str(" },\n");
        }
        out.push_str("    ] },\n");
    }
    out.push_str("  ], providers);\n}\n");
    Ok(out)
}

fn fields(out: &mut String, fs: &[Field]) {
    out.push('[');
    for (n, f) in fs.iter().enumerate() {
        if n != 0 {
            out.push(',');
        }
        let _ = write!(out, "[{},", quoted(&f.name));
        codec(out, &f.value);
        out.push(']');
    }
    out.push(']');
}

fn codec(out: &mut String, v: &Value) {
    match v {
        Value::Void => out.push_str("runtime.unit"),
        Value::Bool => out.push_str("runtime.bool"),
        Value::Char => out.push_str("runtime.char"),
        Value::F32 => out.push_str("runtime.f32"),
        Value::F64 => out.push_str("runtime.f64"),
        Value::String => out.push_str("runtime.str"),
        Value::Bytes => out.push_str("runtime.bytes"),
        Value::Json => out.push_str("runtime.json"),
        Value::Int { bits, signed } => {
            let _ = write!(out, "runtime.int({bits},{signed})");
        }
        Value::Handle(module) => {
            let _ = write!(out, "runtime.handle({})", quoted(module));
        }
        Value::List(t) | Value::Option(t) => {
            out.push_str(if matches!(v, Value::List(_)) {
                "runtime.list("
            } else {
                "runtime.option("
            });
            codec(out, t);
            out.push(')');
        }
        Value::Tuple(ts) => {
            out.push_str("runtime.tuple([");
            for (n, t) in ts.iter().enumerate() {
                if n != 0 {
                    out.push(',');
                }
                codec(out, t);
            }
            out.push_str("])");
        }
        Value::Record(fs) => {
            out.push_str("runtime.record(");
            fields(out, fs);
            out.push(')');
        }
        Value::Enum(vs) => {
            out.push_str("runtime.enumeration([");
            for (n, v) in vs.iter().enumerate() {
                if n != 0 {
                    out.push(',');
                }
                let _ = write!(out, "[{},", quoted(&v.name));
                fields(out, &v.fields);
                out.push(']');
            }
            out.push_str("])");
        }
        Value::Result(a, b) => {
            out.push_str("runtime.result(");
            codec(out, a);
            out.push(',');
            codec(out, b);
            out.push(')');
        }
    }
}

fn quoted(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\u{0000}'..='\u{001f}' | '\u{2028}' | '\u{2029}' => {
                let _ = write!(out, "\\u{:04x}", u32::from(c));
            }
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Write as _;
    use std::process::{Command, Stdio};

    #[test]
    fn ordinary_programs_emit_no_glue() {
        assert_eq!(generate(&Contract::default()).unwrap(), "");
    }

    #[test]
    fn generated_module_is_executable_data_safe_and_signature_specific() {
        let mut c = crate::schema::tests::sample();
        // Raw names cannot inject module code, alter prototypes, or break strings.
        c.interfaces[0].methods[0].name = "__proto__\"\\\n\u{2028}".into();
        let glue = generate(&c).unwrap();
        let script = format!(
            r"
const {{ bind, contract, abiVersion, defineProvider, interfaces }} = await import('data:text/javascript,' + encodeURIComponent({}));
const implementation = {{}};
const provider = defineProvider(interfaces[0].selectors[0], implementation);
if (provider.implementation !== implementation || provider.identity !== interfaces[0].identity) throw Error('provider identity lost');
if (defineProvider(provider.identity, implementation).module !== provider.module) throw Error('exact identity lookup failed');
if (!Object.isFrozen(provider) || !Object.isFrozen(provider.identity)) throw Error('mutable identity');
contract.fill(0);
if (provider.contract[0] !== 1 || defineProvider(provider.module, implementation).contract[0] !== 1) throw Error('exported bytes altered registration');
for (const bad of ['missing', interfaces[0].identity.trait_path, interfaces[0].identity.trait_path.split('.').at(-1)]) {{
  let refused = false;
  try {{ defineProvider(bad, implementation); }} catch {{ refused = true; }}
  if (!refused) throw Error('unqualified provider selector accepted');
}}
let called = 0;
const runtime = new Proxy({{
  bind(bytes, interfaces, providers) {{
    if (abiVersion !== 1 || bytes.length !== contract.length) throw Error('wrong ABI');
    if (interfaces[0].methods[0].name !== {}) throw Error('name changed');
    if (interfaces[0].methods[0].wait !== 'may' || interfaces[1].methods[0].wait !== 'never') throw Error('wait changed');
    if (interfaces[0].methods[0].params.length !== 13) throw Error('parameters changed');
    if (interfaces[0].methods[0].params[2] !== 'int:64,true') throw Error('integer type changed');
    if (interfaces[0].methods[0].params[11] !== 'record:text,str') throw Error('record fields lost');
    if (providers !== 17) throw Error('registration changed');
    called++;
    return interfaces;
  }}
}}, {{ get(o, k) {{ return k in o ? o[k] : ['unit','bool','char','f32','f64','str','bytes','json'].includes(k) ? k : (...xs) => k + ':' + xs.flat(Infinity).join(','); }} }});
bind(runtime, 17);
if (called !== 1) throw Error('binding missing');
console.log('generated glue ok');
",
            quoted(&glue),
            quoted(&c.interfaces[0].methods[0].name)
        );
        let mut child = Command::new("node")
            .args(["--input-type=module"])
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .expect("Node for JS adapter tests");
        child
            .stdin
            .take()
            .unwrap()
            .write_all(script.as_bytes())
            .unwrap();
        let out = child.wait_with_output().unwrap();
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stderr)
        );
        assert_eq!(out.stdout, b"generated glue ok\n");
    }
}
