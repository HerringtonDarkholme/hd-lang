// Checked-in, implementation-neutral runtime cases for issue #1300.
// Run: node spec/tools/generate-erased-call-matrix.ts [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const prefix = "runtime/valid/erased-call-matrix-";
const shapes = ["generic", "dyn", "closure"] as const;
const arguments_ = ["ref", "mut", "value"] as const;
const receivers = ["ref", "mut", "value"] as const;
const elements = ["i32", "string", "unique"] as const;
const rows: string[] = [];
let count = 0;

function output(path: string, contents: string) {
  const full = resolve(root, path);
  if (check) {
    if (readFileSync(full, "utf8") !== contents) {
      throw new Error(`generated file is stale: ${path}`);
    }
  } else {
    writeFileSync(full, contents);
  }
}

const callKinds = shapes.flatMap((shape) => arguments_.map((argument) => ({ shape, argument })));
const cases = callKinds.flatMap(({ shape, argument }) =>
  receivers.flatMap((receiver) =>
    elements.map((element) => ({ shape, argument, receiver, element })),
  ),
);
for (const { shape, argument, receiver, element } of cases) {
  const name = `${shape}-${argument}-${receiver}-${element}`;
  const path = `${prefix}${name}.hd`;
  const recv = { ref: "&self", mut: "&mut self", value: "self" }[receiver];
  const arg = { ref: "&T", mut: "&mut T", value: "T" }[argument];
  const ret = argument === "value" ? "T" : "usize";
  const action = argument === "value" ? "value" : "value.value()";
  const bump = argument === "mut" ? "        value.bump()\n" : "";
  const mutation = receiver === "mut" ? "        self.calls += 1\n" : "";
  let route: string;
  let extra = "";
  if (shape === "closure") {
    const body =
      argument === "mut" ? `\n            value.bump()\n            ${action}` : ` ${action}`;
    route = `        apply := fn(value: ${arg}) -> ${ret}:${body}\n        apply(value)`;
  } else {
    const generic = shape === "generic" ? "[T < ?Copy & Item]" : "";
    const parameter = shape === "dyn" ? "[T < ?Copy & Item]" : "";
    extra = `\ntrait Relay${parameter}:\n    fn apply${generic}(${recv}, value: ${arg}) -> ${ret}\n\nstruct Hop: pass\n\nimpl${shape === "dyn" ? "[T < ?Copy & Item]" : ""} Relay${shape === "dyn" ? "[T]" : ""} for Hop:\n    fn apply${generic}(${recv}, value: ${arg}) -> ${ret}:\n${bump}        ${action}\n`;
    const lend = receiver === "mut" ? "&mut" : "&";
    route =
      shape === "generic"
        ? "        let mut hop = Hop {}\n        hop.apply(value)"
        : `        let mut hop = Hop {}\n        let relay: ${lend} dyn Relay[T] = ${lend} hop\n        relay.apply(value)`;
  }
  const concrete = element === "unique" ? "Parcel" : element;
  const unique = element === "unique";
  const types = {
    unique: `use std.collections.UniqList\n\nstruct Parcel:\n    words: UniqList[string]\n\nimpl !Copy for Parcel\n\nimpl Item for Parcel:\n    fn value(&self) -> usize: self.words.len()\n    fn bump(&mut self) -> void: self.words.push("extra")\n\nfn make(round: usize) -> Parcel:\n    let mut words = UniqList::[string].new()\n    words.push("word_$round")\n    words.push("tail_$round")\n    Parcel { words: words }\n`,
    i32: `impl Item for i32:\n    fn value(&self) -> usize: usize(*self)\n    fn bump(&mut self) -> void: *self = *self + 1\n\nfn make(round: usize) -> i32: i32(round + 7)\n`,
    string: `impl Item for string:\n    fn value(&self) -> usize: self.len()\n    fn bump(&mut self) -> void: *self = *self + "!"\n\nfn make(round: usize) -> string: "word_$round"\n`,
  }[element];
  const lend = receiver === "mut" ? "&mut" : "&";
  const callArg = { ref: "&item", mut: "&mut item", value: "item" }[argument];
  const result =
    argument === "value"
      ? `            back := driver.run(${callArg})\n            assert_equal(back.value(), before, reason="the moved result remains usable")`
      : `            result := driver.run(${callArg})\n            assert_equal(result, before${argument === "mut" ? " + 1" : ""}, reason="the erased call returns the value")\n            assert_equal(item.value(), before${argument === "mut" ? " + 1" : ""}, reason="the caller observes the borrow")`;
  const observed = argument === "value" ? "back" : "item";
  const contentCheck = unique
    ? `\n            assert_equal(\n                ${observed}.words.get_ref(0).expect("first word"),\n                &"word_$round",\n                reason="the nested buffer keeps its original element",\n            )`
    : "";
  const contents = `# test: erased call matrix ${name}\n# expect: test\n# Generated by spec/tools/generate-erased-call-matrix.ts; edit the generator.\n# Rules: trait.dyn.safe.method-type-param, ref.generic.local.\n${types}\ntrait Item < ?Copy:\n    fn value(&self) -> usize\n    fn bump(&mut self) -> void\n\ntrait Driver:\n    fn run[T < ?Copy & Item](${recv}, value: ${arg}) -> ${ret}\n\nstruct Worker:\n    calls: usize\n\nimpl Driver for Worker:\n    fn run[T < ?Copy & Item](${recv}, value: ${arg}) -> ${ret}:\n${mutation}${route}\n${extra}\ntests:\n    it("${name} preserves its argument and receiver"):\n        for round in 0..8:\n            let mut worker = Worker { calls: 0 }\n            let mut item: ${concrete} = make(round)\n            before := item.value()\n            let driver: ${lend} dyn Driver = ${lend} worker\n${result}${contentCheck}\n            assert_equal(worker.calls, ${receiver === "mut" ? "1" : "0"}, reason="receiver effects reach the caller")\n`;
  const formatted = contents
    .replaceAll("& dyn", "&dyn")
    .replaceAll("= & ", "= &")
    .replace(
      /^([ \t]*)fn (.*\) -> [^:\n]+): (.+)$/gm,
      (_, indent: string, signature: string, body: string) =>
        `${indent}fn ${signature}:\n${indent}    ${body}`,
    );
  output(`conformance/${path}`, formatted);
  rows.push(
    `${path}\truntime\taccept\t${unique ? "std/collections.md#r-std-collections.uniq-list.type" : "lang/09-traits.md#r-trait.dyn.safe.method-type-param"}`,
  );
  count += 1;
}

const indexPath = "conformance/cases.tsv";
const old = readFileSync(resolve(root, indexPath), "utf8");
const index = old.split("\n").filter((line) => line && !line.startsWith(prefix));
output(indexPath, `${[...index, ...rows].join("\n")}\n`);
console.log(`${check ? "checked" : "generated"} ${count} erased-call cases`);
