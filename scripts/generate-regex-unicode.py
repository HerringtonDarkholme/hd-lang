#!/usr/bin/env python3
"""Generate regex tables from pinned Unicode 17.0.0 UCD files.

Usage: python3 scripts/generate-regex-unicode.py UCD_DIRECTORY --hd target/debug/hd [--check]
Inputs: UnicodeData.txt, Scripts.txt and CaseFolding.txt from
https://www.unicode.org/Public/17.0.0/ucd/ (Unicode data license).
Cost: sort/merge the input ranges and simple-fold equivalence classes;
never enumerate the Unicode scalar space. Output is deterministic.
"""
from collections import defaultdict
from pathlib import Path
import json
import hashlib
import argparse
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
EXPECTED = {'UnicodeData.txt': '2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c', 'Scripts.txt': '9f5e50d3abaee7d6ce09480f325c706f485ae3240912527e651954d2d6b035bf', 'CaseFolding.txt': 'ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183'}
ALPHABET = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_"


def packed(value):
    out = ""
    while value >= 32:
        out += ALPHABET[32 | (value & 31)]
        value >>= 5
    return out + ALPHABET[value]


def normalize(ranges):
    out = []
    for low, high in sorted(ranges):
        if out and low <= out[-1][1] + 1:
            out[-1] = out[-1][0], max(high, out[-1][1])
        else:
            out.append((low, high))
    return out


def complement(ranges):
    out, low = [], 0
    for start, end in normalize(ranges):
        if low < start:
            out.append((low, start - 1))
        low = end + 1
    if low <= 0x10FFFF:
        out.append((low, 0x10FFFF))
    return out


def property_bytes(ranges):
    out, previous = "", -1
    for low, high in normalize(ranges):
        out += packed(low - previous - 1) + packed(high - low)
        previous = high
    return out


def generate(directory, formatter, check):
    for name, expected in EXPECTED.items():
        if hashlib.sha256((directory / name).read_bytes()).hexdigest() != expected:
            raise ValueError(f"{name} does not match pinned Unicode 17.0.0")
    categories = defaultdict(list)
    pending = None
    for line in (directory / "UnicodeData.txt").read_text().splitlines():
        fields = line.split(";")
        point = int(fields[0], 16)
        if fields[1].endswith(", First>"):
            pending = point
        elif fields[1].endswith(", Last>"):
            categories[fields[2]].append((pending, point))
            pending = None
        else:
            categories[fields[2]].append((point, point))
    assigned = [r for ranges in categories.values() for r in ranges]
    categories["Cn"] = complement(assigned)
    for name in sorted(list(categories)):
        categories[name[0]].extend(categories[name])
    scripts = defaultdict(list)
    for line in (directory / "Scripts.txt").read_text().splitlines():
        text = line.split("#")[0].strip()
        if not text:
            continue
        points, name = map(str.strip, text.split(";"))
        bounds = points.split("..")
        scripts[name].append((int(bounds[0], 16), int(bounds[-1], 16)))
    properties = dict(categories, **scripts, Any=[(0, 0x10FFFF)])
    parent = {}

    def find(point):
        parent.setdefault(point, point)
        while parent[point] != point:
            parent[point] = parent[parent[point]]
            point = parent[point]
        return point

    for line in (directory / "CaseFolding.txt").read_text().splitlines():
        fields = [v.strip() for v in line.split("#")[0].split(";")]
        if len(fields) >= 3 and fields[1] in ("C", "S"):
            source, target = int(fields[0], 16), int(fields[2], 16)
            parent[find(source)] = find(target)
    groups = defaultdict(list)
    for point in sorted(parent):
        groups[find(point)].append(point)
    fold = []
    for members in groups.values():
        fold.extend((a, b) for a in members for b in members if a != b)
    fold.sort()
    blob, previous = "", 0
    for source, target in fold:
        delta = target - source
        blob += packed(source - previous) + packed(delta * 2 if delta >= 0 else -delta * 2 - 1)
        previous = source
    lines = [
        "# Generated by scripts/generate-regex-unicode.py; do not edit.",
        "# Unicode 17.0.0: sorted scalar ranges, delta-coded base32 varints.",
        "# Source: https://www.unicode.org/Public/17.0.0/ucd/",
        "# Unicode data license: https://www.unicode.org/license.txt",
        "use std.rt.{bytes_at, bytes_len}",
        "",
        "# Binary search selects one property; only its ranges are decoded.",
        "pub fn unicode_property(name: string) -> List[i32]?:",
        "    names := [" + ", ".join(json.dumps(k) for k in sorted(properties)) + "]",
        "    data := [" + ", ".join(json.dumps(property_bytes(properties[k])) for k in sorted(properties)) + "]",
        "    let low: usize = 0",
        "    let high = names.len()",
        "    while low < high:",
        "        mid := low + (high - low) / 2",
        "        if names[mid] < name:",
        "            low = mid + 1",
        "        else:",
        "            high = mid",
        "    if low == names.len() || names[low] != name:",
        "        return .None",
        "    text := data[low]",
        "    let mut at: usize = 0",
        "    let previous = -1",
        "    let mut out: List[i32] = []",
        "    while at < bytes_len(text):",
        "        first := read_number(text, &mut at)",
        "        width := read_number(text, &mut at)",
        "        start := previous + 1 + first",
        "        previous = start + width",
        "        out.push(start)",
        "        out.push(previous)",
        "    .Some(out)",
        "",
        "# Complete simple-fold equivalence pairs, in source order.",
        "pub fn unicode_folds() -> List[i32]:",
        "    text := " + json.dumps(blob),
        "    let mut at: usize = 0",
        "    let source = +0",
        "    let mut out: List[i32] = []",
        "    while at < bytes_len(text):",
        "        source += read_number(text, &mut at)",
        "        encoded := read_number(text, &mut at)",
        "        delta := if encoded % 2 == 0: encoded / 2 else: -(encoded / 2) - 1",
        "        out.push(source)",
        "        out.push(source + delta)",
        "    out",
        "",
        "fn read_number(text: string, at: &mut usize) -> i32:",
        "    let value = +0",
        "    let shift: u32 = 0",
        "    while true:",
        "        byte := bytes_at(text, *at)",
        "        *at += 1",
        "        digit := if byte >= 48 && byte <= 57: i32(byte) - 48 else if byte >= 65 && byte <= 90: i32(byte) - 55 else if byte <= 122 && byte >= 97: i32(byte) - 61 else if byte == 45: +62 else: +63",
        "        value = value | ((digit & 31) << shift)",
        "        if digit < 32:",
        "            return value",
        "        shift += 5",
    ]
    output = ROOT / "lib/std/regex/unicode.hd"
    # One formatter process over the generated text; no compiler per row.
    with tempfile.TemporaryDirectory(prefix="regex-unicode-", dir=ROOT / "target") as scratch:
        candidate = Path(scratch) / "unicode.hd"
        candidate.write_text("\n".join(lines) + "\n")
        subprocess.run([str(formatter.resolve()), "fmt", str(candidate)], check=True, timeout=10)
        text = candidate.read_text()
    if check:
        if output.read_text() != text:
            raise ValueError("generated regex Unicode table is stale")
    else:
        output.parent.mkdir(exist_ok=True)
        output.write_text(text)
    print(f"{len(properties)} properties, {len(fold)} fold pairs, {len(text.encode())} source bytes")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    parser.add_argument("--hd", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    generate(options.directory, options.hd, options.check)
